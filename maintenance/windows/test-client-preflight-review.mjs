import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { promisify } from 'node:util';
import { execFile } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const scratch=process.argv[2];
if(!scratch)throw Error('Supply exact task scratch');
const root=await fs.mkdtemp(path.join(scratch,'preflight-review-fixture-'));
const cache=path.join(root,'profile/prompt-data-cache');
await fs.mkdir(cache,{recursive:true});
await fs.writeFile(path.join(root,'candidate.json'),JSON.stringify({version:'0.0.0'}));
await fs.writeFile(path.join(cache,'prompts-0.0.0.json'),JSON.stringify({prompts:[]}));
await fs.writeFile(path.join(root,'profile/systemPromptOriginalHashes.json'),'{}');
const run=()=>promisify(execFile)(process.execPath,[fileURLToPath(new URL('./review-client-preflight.mjs',import.meta.url)),root],{windowsHide:true});
await fs.writeFile(path.join(root,'prompt-preflight.log'),'Error: applyIdentifierMapping failed\n');
await assert.rejects(run(),/did not finish/);
await fs.writeFile(path.join(root,'prompt-preflight.log'),'[new-kind] x (site 1)\n1 finding(s): 1 error(s), 0 warning(s), 0 info.\n');
await assert.rejects(run(),/Unparsed community findings/);
await fs.writeFile(path.join(root,'prompt-preflight.log'),'0 findings.\n');
await run();
assert.equal(JSON.parse(await fs.readFile(path.join(root,'preflight-review.json'),'utf8')).total,0);
await fs.rename(path.join(root,'profile/systemPromptOriginalHashes.json'),path.join(root,'unused-hash-index.json'));
await fs.mkdir(path.join(root,'profile/system-prompts'));
await fs.writeFile(path.join(cache,'prompts-0.0.0.json'),JSON.stringify({prompts:[{id:'stock-note',version:'0.0.0',pieces:['Original stock text.'],identifiers:[]}]}));
await fs.writeFile(path.join(root,'profile/system-prompts/stock-note.md'),'Original stock text.');
await fs.writeFile(path.join(root,'prompt-preflight.log'),'[cardinality] stock-note (site 0): no native site\n1 finding(s): 0 error(s), 1 warning(s), 0 info.\n');
await run();
assert.equal(JSON.parse(await fs.readFile(path.join(root,'preflight-review.json'),'utf8')).unchanged,1);
await fs.writeFile(path.join(root,'profile/system-prompts/stock-note.md'),'User changed text.');
await run();
assert.equal(JSON.parse(await fs.readFile(path.join(root,'preflight-review.json'),'utf8')).changedOrUnresolved.length,1);
console.log(JSON.stringify({passed:true,incompleteOutputRejected:true,unknownFindingRejected:true,completeCleanOutputAccepted:true,missingOptionalHashIndexAccepted:true,editedTextStillUnresolved:true,fixture:root}));
