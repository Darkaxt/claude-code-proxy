// Supply the exact pinned community source and an attributable disposable root.
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { adaptClientAuthorization, body, digest, overrideUrl, promptId, reviewedCommunitySha256 } from './adapt-client-authorization.mjs';
const [sourcePath, scratch] = process.argv.slice(2);
if (!sourcePath || !scratch) throw Error('Supply community source and task scratch');
const source = await fs.readFile(sourcePath, 'utf8');
assert.equal(digest(source), reviewedCommunitySha256, 'Test must exercise the reviewed real community input');
const root = await fs.mkdtemp(path.join(scratch, 'authorization-fixture-'));
const profile = path.join(root, 'profile');
const sourceFile = path.join(root, 'prompt-source/system-prompts-lcc', `${promptId}.md`);
const target = path.join(profile, 'system-prompts', `${promptId}.md`);
await fs.mkdir(path.dirname(sourceFile), { recursive: true });
await fs.mkdir(path.dirname(target), { recursive: true });
await fs.writeFile(sourceFile, source);
await fs.writeFile(target, source);
await fs.writeFile(path.join(root, 'candidate.json'), JSON.stringify({ schema: 'claudegpt.client_candidate.v1', profile }));
const result = await adaptClientAuthorization(root);
const replacement = await fs.readFile(overrideUrl, 'utf8');
assert.equal(await fs.readFile(target, 'utf8'), replacement);
assert.equal(result.revision, 'auth1');
assert.equal(result.adaptedBodySha256, digest(body(replacement)));
assert.deepEqual(await adaptClientAuthorization(root), result, 'Repeat preparation must be idempotent');
const oldParts = body(source).split(/\r?\n\r?\n/);
const newParts = body(replacement).split(/\r?\n\r?\n/);
for (const i of [1, 3, 4]) assert.equal(newParts[i], oldParts[i]);
await fs.writeFile(target, replacement + '\nOwner edit\n');
await assert.rejects(adaptClientAuthorization(root), /local edits/);
assert.equal(await fs.readFile(target, 'utf8'), replacement + '\nOwner edit\n');
await fs.writeFile(target, replacement);
await fs.writeFile(sourceFile, source + '\nUpstream change\n');
await assert.rejects(adaptClientAuthorization(root), /community prompt changed/);
assert.equal(await fs.readFile(target, 'utf8'), replacement);
console.log(JSON.stringify({ passed: true, realPinnedInput: true, adaptationAndIdempotence: true, provenanceCredentialsAndReportingUnchanged: true, localEditsPreserved: true, upstreamDriftRefused: true, fixtureRoot: root }));
